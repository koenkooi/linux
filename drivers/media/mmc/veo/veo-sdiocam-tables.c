/*
 * Constant tables of the HP Photosmart Mobile / Veo SDIO camera bridge.
 *
 * The quantiser, DQT, DHT and sensor tables were extracted as data from the
 * factory Windows CE driver (veosdiocam.dll, SHA-256 17933be7afa4...2ca86):
 * chip quantiser tables at file offset 0x21f80, host DQT segments at 0x21de8,
 * the standard Annex K DHT at 0x21868 and the sensor register list at
 * 0x21a20. Each chip table byte is (m << 3) | e with 64 / q ~= m / 2^e, in
 * zigzag order, luma then chroma: the reciprocal of the DQT segment with the
 * same index, which is why the two must always be used as a pair.
 */

